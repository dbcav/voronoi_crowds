// Checks the discrete mean field game solver: mass conservation, positivity,
// and the adjoint identity  sum_i |V_i| m0_i u_i(0) = total cost paid along the flow.
// Run from this folder:  node check_mfg.js [scene] [cells] [mesh]
require("../js/voronoi.js"); require("../js/shapes.js"); require("../js/mfg.js");

const S = new VC.MFG();
Object.assign(S.p, { scene: process.argv[2] || "twodoors", cells: +(process.argv[3] || 800), mesh: process.argv[4] || "lloyd" });
let t0 = performance.now();
const M = S.buildMesh();
const R = S.solveSync();
const ms = performance.now() - t0;

const Nt = S.p.steps, dt = S.p.T / Nt;
let massErr = 0, minM = Infinity;
for (const m of R.mHist) {
  let s = 0;
  for (let i = 0; i < M.n; i++) { s += M.area[i] * m[i]; minM = Math.min(minM, m[i]); }
  massErr = Math.max(massErr, Math.abs(s - 1));
}

// forward cost along the flow generated by the final controls
const flow = S.solveFP(R.m0, R.bHist);
let J = 0;
for (let t = 0; t < Nt; t++) {
  const b = R.bHist[t], m = flow[t + 1];
  for (let i = 0; i < M.n; i++) {
    let L = 0;
    for (let k = M.start[i]; k < M.start[i + 1]; k++) L += 0.5 * M.tau[k] * b[k] * b[k];
    J += dt * (m[i] * L + M.area[i] * m[i] * R.kappa * R.mHist[t + 1][i]);
  }
}
for (let i = 0; i < M.n; i++) J += M.area[i] * flow[Nt][i] * R.g[i];
let V0 = 0;
for (let i = 0; i < M.n; i++) V0 += M.area[i] * R.m0[i] * R.uHist[0][i];

console.log(`${S.p.scene}, ${S.p.mesh} mesh, ${M.n} cells: solved in ${ms.toFixed(0)} ms`);
console.log(`mass drift ${massErr.toExponential(2)}, smallest density ${minM.toExponential(2)}`);
console.log(`average cost to go at t=0 ${V0.toFixed(10)}`);
console.log(`cost paid along the flow   ${J.toFixed(10)}`);
console.log(`fictitious-play gap: first ${R.residuals[0].toExponential(2)}, last ${R.residuals[R.residuals.length - 1].toExponential(2)}`);
